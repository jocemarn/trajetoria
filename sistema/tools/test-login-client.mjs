import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const php=fs.readFileSync(new URL('../private/releases/1.0.0/app/login.php',import.meta.url),'utf8');
const js=php.split('<script>')[1].split('</script>')[0];
const requests=[];let seq=0;let failContext=false;let failLogin=false;
const elements=new Map();
const context={document:{querySelector(s){if(!elements.has(s))elements.set(s,{});return elements.get(s);}},location:{search:''},FormData:class{},Date,console,fetch:async(url,opts)=>{requests.push({url,opts});if(url.startsWith('/api/auth/context'))return {ok:!failContext,json:async()=>failContext?{error:'Sessão indisponível'}:{csrf:String(++seq).padStart(64,'a')}};return {ok:!failLogin,json:async()=>failLogin?{error:'Conta, senha ou autorização inválida.'}:{ok:true,csrf:'f'.repeat(64)}};}};
vm.createContext(context);vm.runInContext(js,context);
await vm.runInContext("send('login',{login:'teste',password:'teste'})",context);
assert.equal(requests.length,2);assert.match(requests[0].url,/^\/api\/auth\/context\?t=/);
assert.equal(requests[0].opts.cache,'no-store');assert.equal(requests[0].opts.credentials,'same-origin');
assert.equal(requests[1].opts.headers['X-CSRF-Token'],'1'.padStart(64,'a'));
await vm.runInContext("send('password',{current:'teste',password:'nova'})",context);
assert.equal(requests[3].opts.headers['X-CSRF-Token'],'2'.padStart(64,'a'));
failContext=true;const before=requests.length;await assert.rejects(vm.runInContext("send('login',{})",context),/Sessão indisponível/);assert.equal(requests.length,before+1);
failContext=false;failLogin=true;const next=requests.length;await assert.rejects(vm.runInContext("send('login',{})",context),/autorização inválida/);assert.equal(requests.length,next+2);
assert(!php.includes("j($_SESSION['csrf'])"));
console.log('OK: token atualizado antes de login e troca de senha, sem cache, cookies da origem e sem reenvio automático de credenciais.');
